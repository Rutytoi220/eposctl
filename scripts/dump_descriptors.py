#!/usr/bin/env python3
"""Dump and decode all USB HID Report Descriptors for EPOS (VID 0x1395) hidraw devices.

Reads /sys/class/hidraw/hidraw*/device/report_descriptor directly (does not require
root privileges on Linux) and writes a structured Markdown map to docs/HID_DESCRIPTORS.md.
"""

from __future__ import annotations

import argparse
import sys
from datetime import datetime, timezone
from pathlib import Path

# Allow running directly without installing the package first
REPO_ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = REPO_ROOT / "src"
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from eposctl.constants import SUPPORTED_PIDS, VENDOR_ID  # noqa: E402
from eposctl.descriptor import (  # noqa: E402
    HidrawDeviceInfo,
    decode_item_flags,
    discover_hidraw_devices,
    format_descriptor_listing,
)


def render_markdown(devices: list[HidrawDeviceInfo]) -> str:
    """Render decoded HID report descriptors as a Markdown document."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines: list[str] = [
        "# EPOS H3PRO Hybrid — USB HID Report Descriptors",
        "",
        f"Generated by `scripts/dump_descriptors.py` on `{now}`.",
        "",
    ]

    if not devices:
        lines.append("No `hidraw` devices matching `VID=0x1395` were found.")
        return "\n".join(lines) + "\n"

    lines.extend(
        [
            "## Summary",
            "",
            "| Node | VID:PID | Interface | Primary Usage Page | Descriptor Bytes | Reports |",
            "|------|---------|-----------|--------------------|------------------|---------|",
        ]
    )

    for dev in devices:
        desc = dev.descriptor
        up_str = f"`0x{dev.primary_usage_page:04X}`" if dev.primary_usage_page is not None else "N/A"
        raw_len = len(desc.raw) if desc else 0
        rep_summary = (
            ", ".join(
                f"{r.kind} `0x{r.report_id:02X}` ({r.byte_size}B)"
                for r in desc.reports
            )
            if desc and desc.reports
            else "None"
        )
        lines.append(
            f"| `{dev.dev_path}` | `{dev.vendor_id:04x}:{dev.product_id:04x}` | "
            f"`{dev.interface_suffix or dev.phys}` | {up_str} | {raw_len} | {rep_summary} |"
        )

    lines.append("")

    for dev in devices:
        model_name = SUPPORTED_PIDS.get(dev.product_id, dev.name or "Unknown EPOS Device")
        lines.extend(
            [
                f"## `{dev.dev_path}` — `{dev.interface_suffix or dev.phys}` ({model_name})",
                "",
                f"- **VID:PID:** `0x{dev.vendor_id:04X}:0x{dev.product_id:04X}`",
                f"- **HID_NAME:** `{dev.name}`",
                f"- **HID_PHYS:** `{dev.phys}`",
                f"- **HID_UNIQ:** `{dev.uniq}`",
                f"- **DRIVER:** `{dev.driver}`",
            ]
        )

        desc = dev.descriptor
        if desc is None:
            lines.extend(["- **Descriptor:** *Unreadable*", ""])
            continue

        usage_pages_str = ", ".join(f"`0x{up:04X}`" for up in desc.usage_pages) or "None"
        lines.extend(
            [
                f"- **Usage Pages:** {usage_pages_str}",
                f"- **Raw Length:** {len(desc.raw)} bytes",
                "",
                "### Decoded Report Map",
                "",
                "| Report ID | Direction | Usage Page | Payload Bits | Payload Bytes | Total Frame (incl. ID) | Flags |",
                "|-----------|-----------|------------|--------------|---------------|------------------------|-------|",
            ]
        )
        for rep in desc.reports:
            lines.append(
                f"| `0x{rep.report_id:02X}` | {rep.kind} | `0x{rep.usage_page:04X}` | "
                f"{rep.bit_size} | {rep.byte_size} | {rep.total_frame_size} | `{decode_item_flags(rep.flags)}` |"
            )

        raw_hex = " ".join(f"{b:02x}" for b in desc.raw)
        lines.extend(
            [
                "",
                "### Raw Descriptor Hex",
                "",
                "```text",
                raw_hex,
                "```",
                "",
                "### Decoded Item Listing",
                "",
                "```text",
                format_descriptor_listing(desc),
                "```",
                "",
            ]
        )

    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Dump and decode USB HID Report Descriptors for EPOS (VID 0x1395) devices."
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=REPO_ROOT / "docs" / "HID_DESCRIPTORS.md",
        help="Output Markdown path (default: docs/HID_DESCRIPTORS.md)",
    )
    parser.add_argument(
        "--no-write",
        action="store_true",
        help="Print to stdout without writing docs/HID_DESCRIPTORS.md",
    )
    args = parser.parse_args()

    devices = discover_hidraw_devices(vendor_id=VENDOR_ID)
    md = render_markdown(devices)

    if args.no_write:
        print(md)
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(md, encoding="utf-8")
        print(f"Wrote {len(devices)} decoded device descriptor(s) to {args.output}")
        print()
        print(md)

    return 0 if devices else 1


if __name__ == "__main__":
    raise SystemExit(main())
